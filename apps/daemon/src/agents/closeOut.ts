// The close-out of a ticket after merge and QA, written from the event log alone: case.md regenerated in the
// shape of alex's team-dev case template, QA testing notes, and a draft of the Confluence solution page in the
// shape his writing rules give (Acme Shop :: KEY :: <behaviour after the fix>). Pure: the same log gives the same files.
// Publishing the page is a tier-2 request; the files are drafts until he has read them.
import type { SourceRef } from '@elfoqsy/contracts';
import { verdictWords, type RunView, type WorkspaceState } from '@elfoqsy/state';

const day = (ms: number): string => new Date(ms).toISOString().slice(0, 10);
const src = (s: SourceRef): string => (s.kind === 'code' || s.kind === 'log' ? `\`${s.ref}\`` : s.ref);
const sources = (list: SourceRef[] | undefined): string => (list?.length ? ` (${list.map(src).join('; ')})` : '');

/** The ticket's runs, oldest first; a tester's runs are no part of his ticket's record. */
export const runsOf = (s: WorkspaceState, key: string): RunView[] => s.runOrder.map((id) => s.runs[id]!).filter((r) => r.ticket === key && !r.test);

/** "<behaviour after the fix>", from the title its PR was opened with ("feature/SHOP-1: <behaviour>"), if one was. */
export function behaviourOf(s: WorkspaceState, key: string): string | undefined {
  const runIds = new Set(runsOf(s, key).map((r) => r.runId));
  for (const a of Object.values(s.actions)) {
    if (!runIds.has(a.runId) || a.kind !== 'gh.pr.create') continue;
    const title = /--title\s+(?:"([^"]+)"|(\S+))/.exec(a.summary);
    const t = title?.[1] ?? title?.[2];
    if (t) return t.replace(/^(feature|bugfix)\/[A-Z]+-\d+:\s*|^[A-Z]+-\d+:\s*/, '').trim();
  }
  return undefined;
}

function prLines(s: WorkspaceState, key: string): string[] {
  return Object.values(s.prs)
    .filter((p) => p.ticket === key)
    .map((p) => `- ${p.repo} #${p.number}: ${p.state}, CI ${p.checks}. ${p.url}`);
}

/** case.md, regenerated from the log: the checkpoint, scope, provenance, investigation, verification, delivery, decisions. */
export function caseMarkdown(s: WorkspaceState, key: string, now: number, qa?: string): string {
  const t = s.tickets[key];
  const runs = runsOf(s, key);
  const last = runs.at(-1);
  const handoff = last?.handoffId ? s.handoffs[last.handoffId] : undefined;
  const v = [...runs].reverse().find((r) => r.verdict)?.verdict;
  const runIds = new Set(runs.map((r) => r.runId));
  const decisions = Object.values(s.approvals)
    .filter((a) => runIds.has(a.runId) && a.resolution)
    .sort((a, b) => a.requestedAt - b.requestedAt)
    .map((a) => `- ${day(a.requestedAt)}: ${a.question.replace(/\s+/g, ' ').slice(0, 200)} → ${a.resolution!.decision}${a.resolution!.test ? ' (the tester)' : ''}${a.resolution!.answer ? `: ${a.resolution!.answer}` : ''}`);
  const guidance = runs.flatMap((r) => r.guidance.filter((g) => g.by === 'you').map((g) => `- ${day(g.at)}: to Agent ${r.agentNumber}: ${g.text}`));
  const changes = Object.values(s.changes)
    .filter((c) => runIds.has(c.runId))
    .map((c) => `- ${c.target}: before ${c.before}${c.undone ? ' (undone)' : ''}`);
  return [
    `# ${key}`,
    '',
    '## Checkpoint',
    '',
    '- Phase: DONE',
    `- Updated: ${day(now)}, regenerated by Elfoqsy from the event log at close-out`,
    `- Requested mode: ${handoff?.mode ?? last?.mode ?? 'normal'}`,
    '- Next exact action: none',
    `- QA: ${qa ?? 'passed, by Jira status'}`,
    '',
    '## Scope and live Jira snapshot',
    '',
    `- Jira URL: https://acme.atlassian.net/browse/${key}`,
    t ? `- Summary / status / sprint: ${t.summary} / ${t.status} / ${t.sprint || 'none'}` : '- Summary: (not in the sprint any more)',
    t?.storyPoints != null ? `- Existing estimate: ${t.storyPoints} SP` : '- Existing estimate: none',
    ...(handoff?.constraints.length ? [`- Constraints (alex): ${handoff.constraints.map((c) => c.text).join('; ')}`] : []),
    '',
    '## Repository provenance',
    '',
    '| Repo | Branch | Base | Run |',
    '|---|---|---|---|',
    ...runs.flatMap((r) => (r.repos ?? []).map((repo) => `| ${repo} | ${r.branch} | ${r.bases?.[repo] ?? 'default'} | Agent ${r.agentNumber}, ${r.state} |`)),
    '',
    '## Investigation',
    '',
    v ? `- Ticket validity: ${verdictWords(v)}. ${v.summary}` : '- Ticket validity: no verdict was reported',
    ...(v?.symptom ? [`- Reported symptom: "${v.symptom}"`] : []),
    ...(v?.sibling ? [`- Compared with: ${v.sibling}`] : []),
    ...(v?.example ? [`- Expected behaviour: ${v.example.input} → ${v.example.output}`] : []),
    ...(v?.findings ?? []).map((f) => `- ${f.text}${sources(f.sources)}`),
    ...runs.flatMap((r) => (r.hypotheses ?? []).map((h) => `- Hypothesis (${h.status}): ${h.text}${sources(h.evidence)}`)),
    ...runs.flatMap((r) => (r.inputs?.length ? [`- Input classes: ${r.inputs.join('; ')}`] : [])),
    ...runs.flatMap((r) => (r.splitFindings ?? []).map((f) => `- Separate defect, proposed as its own ticket: ${f.summary} ("${f.proposedTicket.summary}")${sources(f.evidence)}`)),
    '',
    '## Implementation and verification',
    '',
    ...runs.flatMap((r) => r.checks.map((c) => `- ${c.description}: ${c.status}${c.evidence ? `. ${c.evidence}` : ''}`)),
    ...(changes.length ? ['', 'Remote changes, recorded before they ran:', ...changes] : []),
    '',
    '## Delivery',
    '',
    ...prLines(s, key),
    `- Close-out: ${day(now)}`,
    '',
    '## Decision history',
    '',
    ...(decisions.length || guidance.length ? [...decisions, ...guidance] : ['- none recorded']),
    '',
  ].join('\n');
}

/** QA testing notes: what changed, what to test (one case per input class), what the run already proved, what it did not. */
export function qaNotes(s: WorkspaceState, key: string): string {
  const runs = runsOf(s, key);
  const v = [...runs].reverse().find((r) => r.verdict)?.verdict;
  const behaviour = behaviourOf(s, key);
  const inputs = runs.flatMap((r) => r.inputs ?? []);
  const proven = runs.flatMap((r) => r.checks.filter((c) => c.status === 'passed').map((c) => `- ${c.description}${c.evidence ? `: ${c.evidence}` : ''}`));
  const open = runs.flatMap((r) => r.checks.filter((c) => c.status !== 'passed').map((c) => `- ${c.description}`));
  return [
    `# ${key}: QA testing notes`,
    '',
    `${behaviour ? `After the fix: ${behaviour}.` : (v?.summary ?? '')}${v?.symptom ? ` Reported: "${v.symptom}".` : ''}`,
    '',
    '## Cases',
    '',
    ...(v?.example ? [`- ${v.example.input} → ${v.example.output}`] : []),
    ...(inputs.length ? inputs.map((i) => `- ${i}`) : ['- The reported scenario, before and after.']),
    '',
    '## Already proven by the run',
    '',
    ...(proven.length ? proven : ['- nothing recorded']),
    ...(open.length ? ['', '## Not proven by the run', '', ...open] : []),
    '',
    '## Changes',
    '',
    ...prLines(s, key),
    '',
  ].join('\n');
}

/** The solution page's draft, as his writing rules lay it out. Its title, and its text. */
export function solutionPage(s: WorkspaceState, key: string): { title: string; text: string } {
  const t = s.tickets[key];
  const runs = runsOf(s, key);
  const v = [...runs].reverse().find((r) => r.verdict)?.verdict;
  const handoff = runs.at(-1)?.handoffId ? s.handoffs[runs.at(-1)!.handoffId!] : undefined;
  const behaviour = behaviourOf(s, key) ?? t?.summary ?? key;
  const proven = runs.flatMap((r) => r.checks.filter((c) => c.status === 'passed').map((c) => `- ${c.description}${c.evidence ? `: ${c.evidence}` : ''}`));
  const title = `Acme Shop :: ${key} :: ${behaviour}`;
  return {
    title,
    text: [
      '## Overview',
      '',
      `${v?.summary ?? behaviour} Jira: ${key}`,
      '',
      '## Problem',
      '',
      `${v?.findings?.[0]?.text ?? t?.summary ?? ''}${v?.symptom ? ` Example: "${v.symptom}".` : v?.example ? ` Example: ${v.example.input} → ${v.example.output}.` : ''}${t ? ` Impact: ${t.priority}.` : ''}`,
      '',
      '## Proposed Solution',
      '',
      `1. ${behaviour}.`,
      ...(handoff?.constraints.length ? [`Unchanged: ${handoff.constraints.map((c) => c.text).join('; ')}.`] : []),
      '',
      '### Scope and Verification',
      '',
      ...(proven.length ? proven : ['- (to fill from the integration test report)']),
      '',
      '## Deliverables',
      '',
      '| Deliverable | Link |',
      '|---|---|',
      ...Object.values(s.prs)
        .filter((p) => p.ticket === key)
        .map((p) => `| ${p.repo} #${p.number} | ${p.url} |`),
      `| Jira | ${key}${t?.storyPoints != null ? `, ${t.storyPoints} SP` : ''} |`,
      '',
    ].join('\n'),
  };
}
